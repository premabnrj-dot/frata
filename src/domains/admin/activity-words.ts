/** What a row did, in words: the map first, then the action's own words ("order.items_edit" → "order items edit"). */
export function actionWords(action: string): string {
  return SAID[action] ?? action.replace(/^module\b/, 'app').replace(/^addon\b/, 'paid app').replace(/^shop\b/, 'store').replace(/[._]+/g, ' ')
}
