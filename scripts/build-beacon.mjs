#!/usr/bin/env node
// Builds the shop's visit beacon (src/beacon/fe.ts) into public/fe.js and writes its content hash to
// src/lib/analytics/beacon-version.ts (the shell loads /fe.js?v=<hash>, cached as immutable: a change is a new URL).
//   node scripts/build-beacon.mjs           build and write both files
//   node scripts/build-beacon.mjs --check   check:beacon — fail if either committed file is stale, the script is over
//                                           its ceiling, or it uses what the beacon must never use (security review
//                                           2026-11-11: href, hash, document.URL, cookies, writing to the page)
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { build } from 'esbuild'

// gzip bytes. Speed review 2026-11-11 suggested 1.6 kB (its prototype 1.2 kB, without A·1's shared parser or the security
// review's checks); built 1,649 B with both. It is async and runs in its own task: 0 ms of TBT at this size.
const CEILING = 1.7 * 1024
const OUT = 'public/fe.js', VERSION = 'src/lib/analytics/beacon-version.ts'
const r = await build({
  entryPoints: ['src/beacon/fe.ts'], bundle: true, minify: true, format: 'iife', target: 'es2020', write: false,
  legalComments: 'none', tsconfig: 'tsconfig.json', logLevel: 'silent',
})
const js = r.outputFiles[0].text
const hash = createHash('sha256').update(js).digest('hex').slice(0, 12)
const version = `// Generated by scripts/build-beacon.mjs from src/beacon/fe.ts: the hash of public/fe.js. Don't edit.\nexport const BEACON_VERSION = '${hash}'\n`
const gz = gzipSync(js).length
const failures = []
if (gz > CEILING) failures.push(`public/fe.js is ${gz} B gzipped (ceiling ${CEILING})`)
for (const [what, re] of [['location.href', /location\.href/], ['location.hash', /location\.hash/], ['document.URL', /document\.URL/], ['cookie', /cookie/i],
  ['innerHTML', /innerHTML|outerHTML|insertAdjacent/], ['a DOM write', /appendChild|\.append\(|\.prepend\(|document\.write/], ['eval', /\beval\(|new Function/]]) {
  if (re.test(js)) failures.push(`public/fe.js uses ${what}`)
}
if (process.argv.includes('--check')) {
  const read = (f) => { try { return readFileSync(f, 'utf8') } catch { return '' } }
  if (read(OUT) !== js) failures.push(`${OUT} is stale — run node scripts/build-beacon.mjs`)
  if (read(VERSION) !== version) failures.push(`${VERSION} is stale — run node scripts/build-beacon.mjs`)
} else if (!failures.length) {
  writeFileSync(OUT, js); writeFileSync(VERSION, version)
}
if (failures.length) { for (const f of failures) console.error(f); console.error(`check:beacon — ${failures.length} problem(s).`); process.exit(1) }
console.log(`check:beacon — clean (public/fe.js ${gz} B gzipped, v ${hash})`)
