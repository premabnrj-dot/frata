#!/usr/bin/env node
// =============================================================================
// FILE: scripts/ekcode-mark.mjs — DRAWS EKCODE'S MARK ONCE (P1 task 8; frata-design-language § EkCode: drawn, never
// typed). Outlines Mukta 700 "एक" and "Code" into SVG paths and writes src/components/ekcode/mark-paths.ts. Not a
// dependency: run with
//   (cd /tmp/x && npm i opentype.js@1.3.4) && NODE_PATH=/tmp/x/node_modules node scripts/ekcode-mark.mjs <Mukta-Bold.ttf>
// (Mukta, SIL Open Font License; Google Fonts). The output is committed; run again only to change the drawing.
// =============================================================================
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const opentype = require('opentype.js')

const file = process.argv[2]
if (!file) { console.error('usage: node scripts/ekcode-mark.mjs <Mukta-Bold.ttf>'); process.exit(2) }
const font = opentype.loadSync(file)
const d = (text, cx, baseline, size, anchor = 'middle') => {
  const w = font.getAdvanceWidth(text, size)
  const x = anchor === 'middle' ? cx - w / 2 : cx
  return font.getPath(text, x, baseline, size).toPathData(2)
}

const out = {
  // Wordmark, viewBox 0 0 330 100: a rounded code box (stroke) with एक inside, a cursor under it, "Code" open beside.
  wordEk: d('एक', 66, 72, 76),
  wordCode: d('Code', 142, 72, 76, 'start'),
  // The box alone, viewBox 0 0 64 64.
  tileEk: d('एक', 32, 42, 36),
  // At 16 px, ए alone, viewBox 0 0 64 64.
  tileE: d('ए', 32, 46, 50),
}
const ts = `// GENERATED by scripts/ekcode-mark.mjs from Mukta 700 (SIL OFL) — do not edit by hand; run the script to redraw.
// EkCode's mark as paths (frata-design-language § EkCode): drawn, never typed.
export const WORD_EK = ${JSON.stringify(out.wordEk)}
export const WORD_CODE = ${JSON.stringify(out.wordCode)}
export const TILE_EK = ${JSON.stringify(out.tileEk)}
export const TILE_E = ${JSON.stringify(out.tileE)}
`
writeFileSync(new URL('../src/components/ekcode/mark-paths.ts', import.meta.url), ts)
console.log('mark-paths.ts written:', Object.entries(out).map(([k, v]) => `${k} ${v.length} chars`).join(', '))
