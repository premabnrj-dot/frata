#!/usr/bin/env node
// =============================================================================
// FILE: scripts/icons/build-icons.mjs — `node scripts/icons/build-icons.mjs <lucide-static dir> <@phosphor-icons/core dir>`
//
// Makes src/domains/icons/data.ts: the shop's curated icon set (Look v4) in three styles — Line from Lucide (ISC),
// Duotone and Solid from Phosphor (MIT) — as element lists, so the shop renders them as inline SVG on the server
// (no icon font, no client script, only the icons a page uses). Get the packages with `npm pack lucide-static
// @phosphor-icons/core` and untar each; nothing is installed. Rerun after changing ICONS below.
// =============================================================================
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [lucideDir, phosphorDir] = process.argv.slice(2)
if (!lucideDir || !phosphorDir) { console.error('usage: node scripts/icons/build-icons.mjs <lucide-static dir> <@phosphor-icons/core dir>'); process.exit(2) }
// name → [lucide icon, phosphor icon]. Commerce first; brand marks only where Phosphor has them (Lucide 1.0 has none).
export const ICONS = {
  bag: ['shopping-bag', 'handbag'], cart: ['shopping-cart', 'shopping-cart-simple'], search: ['search', 'magnifying-glass'],
  user: ['user', 'user'], heart: ['heart', 'heart'], menu: ['menu', 'list'], close: ['x', 'x'], home: ['house', 'house'],
  grid: ['layout-grid', 'squares-four'], truck: ['truck', 'truck'], return: ['undo-2', 'arrow-u-up-left'], cash: ['banknote', 'money'],
  card: ['credit-card', 'credit-card'], lock: ['lock', 'lock'], shield: ['shield-check', 'shield-check'], chat: ['message-circle', 'chat-circle'],
  phone: ['phone', 'phone'], mail: ['mail', 'envelope-simple'], pin: ['map-pin', 'map-pin'], clock: ['clock', 'clock'],
  tag: ['tag', 'tag'], percent: ['percent', 'percent'], sparkle: ['sparkles', 'sparkle'], gift: ['gift', 'gift'], star: ['star', 'star'],
  flame: ['flame', 'fire'], leaf: ['leaf', 'leaf'], ruler: ['ruler', 'ruler'], shirt: ['shirt', 't-shirt'], dress: ['scissors', 'dress'],
  package: ['package', 'package'], store: ['store', 'storefront'], check: ['check', 'check'], arrow: ['arrow-right', 'arrow-right'],
  chevron: ['chevron-down', 'caret-down'], camera: ['camera', 'instagram-logo'], whatsapp: ['message-circle-more', 'whatsapp-logo'],
  globe: ['globe', 'globe'], sun: ['sun', 'sun'], moon: ['moon', 'moon'], crown: ['crown', 'crown'],
}
const nodes = JSON.parse(readFileSync(join(lucideDir, 'icon-nodes.json'), 'utf8'))
const keep = ['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points', 'opacity']
const line = {}, duotone = {}, solid = {}
for (const [name, [l, p]] of Object.entries(ICONS)) {
  const n = nodes[l]; if (!n) throw new Error(`lucide: no ${l}`)
  line[name] = n.map(([tag, a]) => [tag, Object.fromEntries(Object.entries(a).filter(([k]) => keep.includes(k)))])
  for (const [style, out] of [['duotone', duotone], ['fill', solid]]) {
    const svg = readFileSync(join(phosphorDir, 'assets', style, `${p}-${style}.svg`), 'utf8')
    out[name] = [...svg.matchAll(/<path d="([^"]+)"(?: opacity="([\d.]+)")?\/>/g)].map((m) => ['path', m[2] ? { d: m[1], opacity: m[2] } : { d: m[1] }])
    if (!out[name].length) throw new Error(`phosphor: no paths in ${p}-${style}`)
  }
}
const ver = (d) => JSON.parse(readFileSync(join(d, 'package.json'), 'utf8')).version
const body = `// GENERATED by scripts/icons/build-icons.mjs from lucide-static ${ver(lucideDir)} (ISC) and @phosphor-icons/core ${ver(phosphorDir)} (MIT).
// Do not edit by hand. Licences: src/domains/icons/NOTICE.md.
export type IconNode = [string, Record<string, string>]
export const ICON_NAMES = ${JSON.stringify(Object.keys(ICONS))} as const
export type IconName = (typeof ICON_NAMES)[number]
/** Line: Lucide, a 24 box, stroked (the shop's stroke weight applies). */
export const LINE: Record<IconName, IconNode[]> = ${JSON.stringify(line)}
/** Duotone: Phosphor, a 256 box, filled; the tone layer carries its own opacity. */
export const DUOTONE: Record<IconName, IconNode[]> = ${JSON.stringify(duotone)}
/** Solid: Phosphor fill, a 256 box. */
export const SOLID: Record<IconName, IconNode[]> = ${JSON.stringify(solid)}
`
writeFileSync('src/domains/icons/data.ts', body)
console.log(`build-icons: ${Object.keys(ICONS).length} icons × 3 styles, ${Math.round(body.length / 1024)} kB of source`)
