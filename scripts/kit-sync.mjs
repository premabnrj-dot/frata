#!/usr/bin/env node
// The partner kit's copy of the bag link (SA1b D·9): kit/starter/lib/cart-link.ts is generated from
// src/domains/storefront-api/cart-link.ts with the quote's limits written in, so the starter imports nothing from src/.
// `node scripts/kit-sync.mjs` writes it; `--check` fails when the copy is stale (src/domains/storefront-api/__tests__).
import { readFileSync, writeFileSync } from 'node:fs'

export function starterCartLink() {
  const src = readFileSync('src/domains/storefront-api/cart-link.ts', 'utf8')
  const quote = readFileSync('src/domains/checkout/quote.ts', 'utf8')
  const n = (name) => quote.match(new RegExp(`export const ${name} = (\\d+)`))[1]
  return '// GENERATED by scripts/kit-sync.mjs from Frrata\'s src/domains/storefront-api/cart-link.ts. Do not edit here.\n' +
    src.replace("import { MAX_LINES, MAX_QTY } from '@/domains/checkout/quote'", `const MAX_QTY = ${n('MAX_QTY')}\nconst MAX_LINES = ${n('MAX_LINES')}`)
}
/** `npm run frrata`'s own words (G·3, four screens § 2's terminal), from DEVICE_TERMINAL in Frrata's device module: the
 *  start's answer carries the rest (Open, Code) and every refusal carries its own message. */
export function starterFrrataWords() {
  const src = readFileSync('src/domains/storefront-api/device.ts', 'utf8')
  const word = (name) => JSON.stringify(src.match(new RegExp(`  ${name}: '([^']+)'`))[1]).replace(/^"|"$/g, "'")
  return '// GENERATED by scripts/kit-sync.mjs from Frrata\'s src/domains/storefront-api/device.ts. Do not edit here.\n' +
    `export const WAITING = ${word('waiting')}\nexport const DONE = ${word('done')}\n`
}
const OUTS = [['kit/starter/lib/cart-link.ts', starterCartLink], ['kit/starter/scripts/frrata-words.mjs', starterFrrataWords]]
if (process.argv[1]?.endsWith('kit-sync.mjs')) {
  for (const [out, make] of OUTS) {
    if (process.argv.includes('--check')) { if (readFileSync(out, 'utf8') !== make()) { console.error(`${out} is stale: node scripts/kit-sync.mjs`); process.exit(1) } }
    else writeFileSync(out, make())
  }
}
