#!/usr/bin/env node
// The partner kit's copy of the bag link (SA1b D·9): kit/starter/lib/cart-link.ts is generated from
// src/domains/storefront-api/cart-link.ts with the quote's limits written in, so the starter imports nothing from src/.
// `node scripts/kit-sync.mjs` writes it; `--check` fails when the copy is stale (src/domains/storefront-api/__tests__).
import { readFileSync, writeFileSync } from 'node:fs'

export function starterCartLink() {
  const src = readFileSync('src/domains/storefront-api/cart-link.ts', 'utf8')
  const quote = readFileSync('src/domains/checkout/quote.ts', 'utf8')
  const n = (name) => quote.match(new RegExp(`export const ${name} = (\\d+)`))[1]
  return '// GENERATED by scripts/kit-sync.mjs from Frrata\'s src/domains/storefront-api/cart-link.ts. Do not edit here.\n' +
    src.replace("import { MAX_LINES, MAX_QTY } from '@/domains/checkout/quote'", `const MAX_QTY = ${n('MAX_QTY')}\nconst MAX_LINES = ${n('MAX_LINES')}`)
}
const OUT = 'kit/starter/lib/cart-link.ts'
if (process.argv[1]?.endsWith('kit-sync.mjs')) {
  if (process.argv.includes('--check')) { if (readFileSync(OUT, 'utf8') !== starterCartLink()) { console.error(`${OUT} is stale: node scripts/kit-sync.mjs`); process.exit(1) } }
  else writeFileSync(OUT, starterCartLink())
}
